import React, { useState, useRef, useEffect } from 'react';
import { useAppState } from '../context/AppStateContext';
import { Bot, Send, UserCheck, X, AlertTriangle, ShieldCheck, RefreshCw, MessageSquare } from 'lucide-react';

export const AIChatDrawer = ({ isOpen, onClose }) => {
  const { escalateChatToAdmin } = useAppState();

  const [inputMsg, setInputMsg] = useState('');
  const [messages, setMessages] = useState([
    {
      sender: 'ai',
      text: 'Hello! I am LunchMate AI. I can help with OTPs, Tracking, Subscriptions, or Emergency Deliveries. How can I help you today?'
    }
  ]);
  const [isEscalated, setIsEscalated] = useState(false);
  const [isTyping, setIsTyping] = useState(false);
  const messagesEndRef = useRef(null);

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages, isTyping]);

  if (!isOpen) return null;

  const handleSend = () => {
    if (!inputMsg.trim()) return;

    const userText = inputMsg.trim();
    const newMsgs = [...messages, { sender: 'user', text: userText }];
    setMessages(newMsgs);
    setInputMsg('');

    if (isEscalated) {
      // Chat is already connected to Admin Queue
      return;
    }

    setIsTyping(true);

    setTimeout(() => {
      setIsTyping(false);
      const lower = userText.toLowerCase();

      // Check if user requested human admin
      if (lower.includes('human') || lower.includes('admin') || lower.includes('person') || lower.includes('agent') || lower.includes('complain')) {
        setIsEscalated(true);
        const escalatedMsgs = [
          ...newMsgs,
          {
            sender: 'system',
            text: '⚡ Smart Escalation Triggered: Connecting to Live Admin. An Administrator will review your full chat history and reply directly.'
          }
        ];
        setMessages(escalatedMsgs);
        escalateChatToAdmin({
          name: "Parent / Customer",
          phone: "+91 98765 12345",
          role: "Parent",
          reason: "User requested human escalation: " + userText,
          messages: escalatedMsgs
        });
        return;
      }

      // Knowledge Base Auto Responses
      let botReply = "";
      if (lower.includes('otp')) {
        botReply = "🔑 Pickup OTP is generated by the parent when food is packed. Delivery OTP is sent to the School Gate / College Student to ensure 100% safe handover!";
      } else if (lower.includes('price') || lower.includes('cost') || lower.includes('fare') || lower.includes('rate')) {
        botReply = "💰 Delivery rates start at ₹40 for 0-5 km, ₹60 for 5-10 km, and ₹80 for 10-15 km. Drivers receive 85% of all earnings directly.";
      } else if (lower.includes('subscribe') || lower.includes('plan') || lower.includes('monthly')) {
        botReply = "📅 LunchMate offers Daily, Weekly (5 days), and Monthly (22 days) plans. Monthly subscribers save 30% and get free thermal lunch tag tracking!";
      } else if (lower.includes('track') || lower.includes('where') || lower.includes('late')) {
        botReply = "📍 You can track your driver's real-time GPS location in the Parent Portal under 'Track Lunch'. You will receive notifications at each delivery milestone.";
      } else if (lower.includes('driver') || lower.includes('join') || lower.includes('verify')) {
        botReply = "🛵 Delivery partners can sign up on the Driver Portal by submitting Aadhaar, Driving License, PAN, and Selfie for Admin KYC verification.";
      } else {
        botReply = "I understand you are asking about '" + userText + "'. If this doesn't fully resolve your question, click 'Escalate to Human Admin' below to connect immediately.";
      }

      setMessages(prev => [...prev, { sender: 'ai', text: botReply }]);
    }, 900);
  };

  const triggerManualEscalation = () => {
    setIsEscalated(true);
    const escalatedMsgs = [
      ...messages,
      {
        sender: 'system',
        text: '⚡ Chat Handed Over to Human Admin. Admin inbox updated with full conversation history.'
      }
    ];
    setMessages(escalatedMsgs);
    escalateChatToAdmin({
      name: "App User",
      phone: "+91 98444 33221",
      role: "Parent",
      reason: "Manual user request for Admin support",
      messages: escalatedMsgs
    });
  };

  return (
    <div style={{
      position: 'fixed',
      inset: 0,
      zIndex: 9999,
      background: 'rgba(0, 0, 0, 0.7)',
      backdropFilter: 'blur(6px)',
      display: 'flex',
      justifyContent: 'flex-end'
    }}>
      <div style={{
        width: '100%',
        maxWidth: '440px',
        height: '100%',
        background: '#0F172A',
        borderLeft: '1px solid rgba(255, 94, 54, 0.3)',
        display: 'flex',
        flexDirection: 'column',
        boxShadow: '-10px 0 30px rgba(0,0,0,0.5)'
      }}>
        {/* Header */}
        <div style={{
          padding: '20px',
          background: 'linear-gradient(135deg, #1E293B 0%, #0F172A 100%)',
          borderBottom: '1px solid rgba(255, 255, 255, 0.1)',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between'
        }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
            <div style={{ background: isEscalated ? '#FF5E36' : '#2EC4B6', padding: '10px', borderRadius: '12px', color: 'white' }}>
              {isEscalated ? <UserCheck size={22} /> : <Bot size={22} />}
            </div>
            <div>
              <h3 style={{ color: 'white', fontSize: '1.1rem' }}>
                {isEscalated ? 'Human Admin Support' : 'AI Support'}
              </h3>
              <p style={{ color: isEscalated ? '#FF9F1C' : '#2EC4B6', fontSize: '0.78rem' }}>
                {isEscalated ? '🟢 Live Admin Escalated Queue' : '🟢 AI Online (Instant Auto-Reply)'}
              </p>
            </div>
          </div>
          <button 
            onClick={onClose}
            style={{ background: 'transparent', border: 'none', color: '#94A3B8', cursor: 'pointer', padding: '4px' }}
          >
            <X size={24} />
          </button>
        </div>

        {/* Messages Body */}
        <div style={{ flex: 1, padding: '20px', overflowY: 'auto', display: 'flex', flexDirection: 'column', gap: '14px' }}>
          {messages.map((msg, index) => (
            <div 
              key={index} 
              style={{
                alignSelf: msg.sender === 'user' ? 'flex-end' : 'flex-start',
                maxWidth: '85%',
                background: msg.sender === 'user' 
                  ? 'linear-gradient(135deg, #FF5E36, #FF8A00)' 
                  : msg.sender === 'system'
                  ? 'rgba(255, 159, 28, 0.15)'
                  : msg.sender === 'admin'
                  ? 'rgba(46, 196, 182, 0.2)'
                  : 'rgba(30, 41, 59, 0.9)',
                color: 'white',
                padding: '12px 16px',
                borderRadius: msg.sender === 'user' ? '18px 18px 4px 18px' : '18px 18px 18px 4px',
                fontSize: '0.9rem',
                border: msg.sender === 'system' ? '1px dashed #FF9F1C' : msg.sender === 'admin' ? '1px solid #2EC4B6' : '1px solid rgba(255,255,255,0.08)',
                lineHeight: '1.4'
              }}
            >
              {msg.sender === 'system' && (
                <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#FF9F1C', fontWeight: 600, marginBottom: '4px', fontSize: '0.8rem' }}>
                  <AlertTriangle size={14} /> Escalation Notification
                </div>
              )}
              {msg.sender === 'admin' && (
                <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#2EC4B6', fontWeight: 600, marginBottom: '4px', fontSize: '0.8rem' }}>
                  <ShieldCheck size={14} /> Official Admin Support
                </div>
              )}
              {msg.text}
            </div>
          ))}

          {isTyping && (
            <div style={{ alignSelf: 'flex-start', background: 'rgba(30, 41, 59, 0.9)', padding: '10px 16px', borderRadius: '18px', color: '#94A3B8', fontSize: '0.85rem', display: 'flex', alignItems: 'center', gap: '8px' }}>
              <RefreshCw size={14} className="animate-spin-slow" /> AI is formulating answer...
            </div>
          )}
          <div ref={messagesEndRef} />
        </div>

        {/* Footer Actions */}
        {!isEscalated && (
          <div style={{ padding: '10px 20px', background: 'rgba(30, 41, 59, 0.5)', borderTop: '1px solid rgba(255,255,255,0.05)', textAlign: 'center' }}>
            <button 
              onClick={triggerManualEscalation}
              style={{
                background: 'transparent',
                border: '1px solid rgba(255, 159, 28, 0.5)',
                color: '#FF9F1C',
                padding: '6px 14px',
                borderRadius: '20px',
                fontSize: '0.78rem',
                cursor: 'pointer',
                display: 'inline-flex',
                alignItems: 'center',
                gap: '6px'
              }}
            >
              <UserCheck size={14} /> Talk to Human Admin Support
            </button>
          </div>
        )}

        {/* Input Box */}
        <div style={{ padding: '16px 20px', background: '#1E293B', borderTop: '1px solid rgba(255,255,255,0.1)', display: 'flex', gap: '10px' }}>
          <input 
            type="text" 
            placeholder={isEscalated ? "Type message to Admin..." : "Ask a question..."}
            value={inputMsg}
            onChange={(e) => setInputMsg(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && handleSend()}
            style={{
              flex: 1,
              background: '#0F172A',
              border: '1px solid rgba(255,255,255,0.15)',
              borderRadius: '20px',
              padding: '10px 16px',
              color: 'white',
              fontSize: '0.9rem',
              outline: 'none'
            }}
          />
          <button 
            onClick={handleSend}
            style={{
              background: 'linear-gradient(135deg, #FF5E36, #FF8A00)',
              border: 'none',
              borderRadius: '50%',
              width: '42px',
              height: '42px',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              color: 'white',
              cursor: 'pointer',
              boxShadow: '0 4px 12px rgba(255, 94, 54, 0.4)'
            }}
          >
            <Send size={18} />
          </button>
        </div>
      </div>
    </div>
  );
};
